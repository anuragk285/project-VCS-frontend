// Fails when code uses colours that are not in our theme (src/index.css).
// Run:  npm run check:colours
// To allow one special line (for example a 3D colour), add the comment  colour-ok  on that line.
import { readdirSync, readFileSync, statSync } from "node:fs"
import { join, extname } from "node:path"

const ROOT = "src"
const SKIP_DIRS = new Set([join("src", "components", "ui")]) // generated by shadcn, already uses our tokens
const EXTS = new Set([".ts", ".tsx", ".jsx", ".js"])

const PALETTE =
  "slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose"
const UTIL =
  "bg|text|border|ring|outline|fill|stroke|from|via|to|divide|placeholder|accent|caret|decoration|shadow"

const RULES = [
  {
    re: new RegExp(`\\b(?:${UTIL})-(?:${PALETTE})-\\d{2,3}\\b`),
    msg: "Tailwind's built-in palette is not allowed. Use a theme colour such as text-primary, bg-card, text-muted-foreground.",
  },
  {
    re: /\b(?:bg|text|border|ring|outline|fill|stroke|from|via|to|divide)-(?:white|black)\b/,
    msg: "Do not use white or black. Use bg-card, bg-background, text-foreground or text-primary-foreground.",
  },
  {
    re: /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b(?![0-9a-zA-Z])/,
    msg: "Do not write hex colours in code. Add a token in index.css or use an existing one.",
  },
  {
    re: /\b(?:rgb|rgba|hsl|hsla|oklch)\(/,
    msg: "Do not write rgb/hsl/oklch colours in code. Use a theme colour.",
  },
  {
    re: /\[(?:#|rgb|hsl|oklch)[^\]]*\]/,
    msg: "Do not use arbitrary colour values like text-[#123456].",
  },
  {
    re: /(?:^|[\s"'`])dark:/,
    msg: "No dark: classes. The site is light only.",
  },
]

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (SKIP_DIRS.has(p)) continue
    const s = statSync(p)
    if (s.isDirectory()) walk(p, out)
    else if (EXTS.has(extname(p))) out.push(p)
  }
  return out
}

let problems = 0
for (const file of walk(ROOT)) {
  readFileSync(file, "utf8").split("\n").forEach((line, i) => {
    if (line.includes("colour-ok")) return
    for (const r of RULES) {
      if (r.re.test(line)) {
        problems++
        console.log(`${file}:${i + 1}  ${r.msg}\n    ${line.trim()}`)
        break
      }
    }
  })
}

if (problems) {
  console.log(`\n${problems} colour problem(s). See the allowed class list in TEAM-SETUP.md.`)
  process.exit(1)
}
console.log("Colour check passed.")
